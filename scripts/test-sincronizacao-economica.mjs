  assert.deepEqual((await playlistChanges(0)).changes,[{playlist_id:'10000000-0000-0000-0000-000000000001',deleted:false}]);
  assert.deepEqual((await playlistChanges(r)).changes,[],'sem alterações não envia novamente playlists');
